export type StrKey = keyof Dict;
const DICTS = { en, ar } as const;

export function translate(lang: "en" | "ar", key: StrKey, vars?: Record<string, string | number>): string {
  let s: string = DICTS[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export type T = (key: StrKey, vars?: Record<string, string | number>) => string;

export function useT(): T {
  const lang = useStore((s) => s.settings.uiLang);
  return (key, vars) => translate(lang, key, vars);
}

export function applyDocumentLang(lang: "en" | "ar") {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
}
