import { describe, expect, it } from "vitest";
import { Course, K, MemoryStore, drawBoard, dueReminders, goalNote, goalPace, planFromObjectives, profileStore, recordEvidence, type Goal, type MasteryMap } from "../src/index.ts";

const plan = planFromObjectives(
  "p1",
  "Fractions",
  Array.from({ length: 10 }, (_, i) => ({ id: `o${i}`, title: `Step ${i}`, summary: "", prereqs: [] })),
);
const at = (d: string) => new Date(`${d}T12:00:00`);

/** Masters the first n objectives. */
function mastered(n: number): MasteryMap {
  let m: MasteryMap = {};
  for (let i = 0; i < n; i++) for (let k = 0; k < 6; k++) m = recordEvidence(m, `o${i}`, "check", true);
  return m;
}

const goal: Goal = { planId: "p1", since: "2026-11-01", due: "2026-11-30", remind: true };

describe("goal pace", () => {
  it("plans the pace from what is left and the days to go", () => {
    const p = goalPace(plan, mastered(5), goal, at("2026-11-16"));
    expect(p).toMatchObject({ left: 5, total: 10, daysLeft: 15, status: "on-track" });
    expect(p.perWeek).toBeCloseTo(2.4, 1);
  });

  it("is behind when progress trails the time used, ahead when it leads", () => {
    expect(goalPace(plan, mastered(1), goal, at("2026-11-20")).status).toBe("behind");
    expect(goalPace(plan, mastered(9), goal, at("2026-11-10")).status).toBe("ahead");
  });

  it("is overdue after the date and done when everything is mastered", () => {
    expect(goalPace(plan, mastered(3), goal, at("2026-12-01"))).toMatchObject({ status: "overdue", daysLeft: 0, perWeek: 7 });
    expect(goalPace(plan, mastered(10), goal, at("2026-12-05")).status).toBe("done");
  });

  it("writes a tutor note that names the date and the pace", () => {
    const note = goalNote(goal, goalPace(plan, mastered(1), goal, at("2026-11-20")));
    expect(note).toContain("2026-11-30");
    expect(note).toContain("behind");
  });
});

describe("reminders", () => {
  it("skips finished goals, goals with reminders off and goals already shown today", () => {
    const other = { ...plan, id: "p2" };
    const items = [
      { goal, plan, mastery: mastered(1) },
      { goal: { ...goal, planId: "p2", due: "2026-11-21" }, plan: other, mastery: mastered(2) },
      { goal: { ...goal, planId: "p3", remind: false }, plan: { ...plan, id: "p3" }, mastery: {} },
      { goal: { ...goal, planId: "p4", remindedOn: "2026-11-20" }, plan: { ...plan, id: "p4" }, mastery: {} },
      { goal: { ...goal, planId: "p5" }, plan: { ...plan, id: "p5" }, mastery: mastered(10) },
    ];
    const r = dueReminders(items, at("2026-11-20"));
    expect(r.map((x) => x.plan.id)).toEqual(["p2", "p1"]);
  });
});

describe("profiles", () => {
  it("keeps each learner's data apart in one store", async () => {
    const root = new MemoryStore();
    const first = profileStore(root, "a", true);
    const second = profileStore(root, "b", false);
    await new Course(first).savePlan(plan);
    await new Course(second).savePlan({ ...plan, id: "p2", title: "Other" });
    await root.set(K.profiles, { list: [], current: "a" });
    expect((await new Course(first).plans()).map((p) => p.id)).toEqual(["p1"]);
    expect((await new Course(second).plans()).map((p) => p.id)).toEqual(["p2"]);
    expect(await first.keys()).toEqual(["plans/p1"]);
    expect(await second.keys()).toEqual(["plans/p2"]);
    expect(await root.keys("p/b/")).toEqual(["p/b/plans/p2"]);
  });

  it("stores goals per course and drops them with the course", async () => {
    const c = new Course(new MemoryStore());
    await c.savePlan(plan);
    await c.saveGoal(goal);
    expect(await c.goals()).toEqual([goal]);
    await c.deletePlan("p1");
    expect(await c.goals()).toEqual([]);
  });
});

describe("drawBoard", () => {
  const beat = (content: string) => ({ say: "Look.", board: { kind: "image" as const, content } });

  it("replaces a gen: prompt with the drawn picture and its source", async () => {
    const out = await drawBoard(beat("gen: a red apple"), async (p) => ({ dataUri: `data:image/png;base64,${p.length}`, source: "Generated by m (P)" }));
    expect(out.board).toEqual({ kind: "image", content: "data:image/png;base64,11", source: "Generated by m (P)" });
  });

  it("drops the board, not the beat, without an image model or when drawing fails", async () => {
    expect((await drawBoard(beat("gen: x"))).board).toBeUndefined();
    const failed = await drawBoard(beat("gen: x"), async () => {
      throw new Error("quota");
    });
    expect(failed).toEqual({ say: "Look." });
  });

  it("leaves other boards alone", async () => {
    const b = beat("https://example.com/a.png");
    expect(await drawBoard(b, async () => ({ dataUri: "", source: "" }))).toBe(b);
  });
});
