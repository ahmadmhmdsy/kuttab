import { describe, expect, it } from "vitest";
import { IMAGE_NOTICE, canMakeImages, makeImage, type FetchFn } from "../src/index.ts";

const json = (body: unknown, status = 200) => new Response(JSON.stringify(body), { status, headers: { "Content-Type": "application/json" } });
const PNG = "iVBORw0KGgo=";

function recorder(reply: (url: string, body: any) => Response) {
  const calls: { url: string; body: any; headers: Headers }[] = [];
  const fetch: FetchFn = async (url, init) => {
    const body = init?.body ? JSON.parse(String(init.body)) : undefined;
    calls.push({ url: String(url), body, headers: new Headers(init?.headers) });
    return reply(String(url), body);
  };
  return { fetch, calls };
}

describe("image generation", () => {
  it("asks a Gemini image model for an image part and returns a data URI with source and notice", async () => {
    const { fetch, calls } = recorder(() => json({ candidates: [{ content: { parts: [{ text: "here" }, { inlineData: { mimeType: "image/png", data: PNG } }] } }] }));
    const img = await makeImage({ provider: "google", model: "gemini-2.5-flash-image" }, { apiKey: "k" }, fetch, "a heart diagram", { aspectRatio: "16:9" });
    expect(calls[0]!.url).toBe("https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash-image:generateContent");
    expect(calls[0]!.headers.get("x-goog-api-key")).toBe("k");
    expect(calls[0]!.body.generationConfig).toEqual({ responseModalities: ["IMAGE"], imageConfig: { aspectRatio: "16:9" } });
    expect(img).toEqual({ dataUri: `data:image/png;base64,${PNG}`, mediaType: "image/png", source: "Generated by gemini-2.5-flash-image (Google Gemini)", notice: IMAGE_NOTICE });
  });

  it("uses predict for Imagen", async () => {
    const { fetch, calls } = recorder(() => json({ predictions: [{ bytesBase64Encoded: PNG, mimeType: "image/png" }] }));
    const img = await makeImage({ provider: "google", model: "imagen-4.0-generate-001" }, { apiKey: "k" }, fetch, "a cell");
    expect(calls[0]!.url).toMatch(/imagen-4\.0-generate-001:predict$/);
    expect(img.dataUri).toBe(`data:image/png;base64,${PNG}`);
  });

  it("calls /images/generations on an OpenAI-compatible server, local ones included", async () => {
    const { fetch, calls } = recorder(() => json({ data: [{ b64_json: PNG }] }));
    const img = await makeImage({ provider: "custom", model: "sd-turbo", baseURL: "http://localhost:8081/v1" }, {}, fetch, "a cat");
    expect(calls[0]!.url).toBe("http://localhost:8081/v1/images/generations");
    expect(calls[0]!.body).toMatchObject({ model: "sd-turbo", prompt: "a cat", n: 1 });
    expect(img.dataUri).toMatch(/^data:image\/png;base64,/);
  });

  it("reports provider errors and refuses providers that cannot draw", async () => {
    const { fetch } = recorder(() => json({ error: { message: "quota" } }, 429));
    await expect(makeImage({ provider: "google", model: "gemini-2.5-flash-image" }, { apiKey: "k" }, fetch, "x")).rejects.toThrow("quota");
    expect(canMakeImages("anthropic")).toBe(false);
    await expect(makeImage({ provider: "anthropic", model: "claude" }, {}, fetch, "x")).rejects.toThrow(/does not make images/);
  });
});
