// Image generation (T-27, decision 0002 item 3). The learner picks an image
// model like any other; with none set the teacher has no image tool. OpenAI and
// OpenAI-compatible servers (cloud or local, e.g. LocalAI or a Stable Diffusion
// server) use /images/generations through the AI SDK. Gemini has no image route
// on its OpenAI-compatible endpoint, so its own generateContent (Gemini image
// models) and predict (Imagen) are called directly.
import { createOpenAI } from "@ai-sdk/openai";
import { createOpenAICompatible } from "@ai-sdk/openai-compatible";
import { generateImage } from "ai";
import { providerInfo, resolveBaseURL, type Credentials, type FetchFn, type ModelRef } from "./providers.ts";

export interface MadeImage {
  /** data:image/...;base64,... */
  dataUri: string;
  mediaType: string;
  /** Who made it, shown under the image: "Generated by <model> (<provider>)". */
  source: string;
  /** Shown with every generated image. */
  notice: string;
}

export const IMAGE_NOTICE =
  "AI-generated image. It may be inaccurate. Reuse is governed by the image provider's terms, not by Kuttab.";

export interface ImageOptions {
  /** "16:9", "1:1", ... */
  aspectRatio?: `${number}:${number}`;
  abortSignal?: AbortSignal;
}

/** Providers that can make images at all. Anthropic cannot. */
export function canMakeImages(provider: string): boolean {
  return provider !== "anthropic" && provider !== "webllm";
}

export async function makeImage(ref: ModelRef, creds: Credentials, fetch: FetchFn, prompt: string, opts: ImageOptions = {}): Promise<MadeImage> {
  const info = providerInfo(ref.provider);
  if (!canMakeImages(ref.provider)) throw new Error(`${info.label} does not make images`);
  const made = ref.provider === "google" ? await gemini(ref, creds, fetch, prompt, opts) : await viaSdk(ref, creds, fetch, prompt, opts);
  return { dataUri: `data:${made.mediaType};base64,${made.base64}`, mediaType: made.mediaType, source: `Generated by ${ref.model} (${info.label})`, notice: IMAGE_NOTICE };
}

async function viaSdk(ref: ModelRef, creds: Credentials, fetch: FetchFn, prompt: string, opts: ImageOptions) {
  const info = providerInfo(ref.provider);
  const baseURL = resolveBaseURL(ref);
  const model =
    info.api === "openai"
      ? createOpenAI({ apiKey: creds.apiKey ?? "", baseURL, fetch }).image(ref.model)
      : createOpenAICompatible({ name: info.id, baseURL, apiKey: creds.apiKey || undefined, headers: info.headers?.(), fetch }).imageModel(ref.model);
  const size = opts.aspectRatio === "16:9" ? "1536x1024" : opts.aspectRatio === "9:16" ? "1024x1536" : "1024x1024";
  const { image } = await generateImage({ model, prompt, n: 1, size: size as `${number}x${number}`, abortSignal: opts.abortSignal, maxRetries: 1 });
  return { base64: image.base64, mediaType: image.mediaType || "image/png" };
}

interface GeminiPart {
  inlineData?: { mimeType?: string; data?: string };
  text?: string;
}

async function gemini(ref: ModelRef, creds: Credentials, fetch: FetchFn, prompt: string, opts: ImageOptions) {
  const base = resolveBaseURL(ref).replace(/\/openai$/, "");
  const headers = { "Content-Type": "application/json", "x-goog-api-key": creds.apiKey ?? "" };
  const imagen = ref.model.startsWith("imagen");
  const url = `${base}/models/${encodeURIComponent(ref.model)}:${imagen ? "predict" : "generateContent"}`;
  const body = imagen
    ? { instances: [{ prompt }], parameters: { sampleCount: 1, ...(opts.aspectRatio ? { aspectRatio: opts.aspectRatio } : {}) } }
    : {
        contents: [{ role: "user", parts: [{ text: prompt }] }],
        generationConfig: { responseModalities: ["IMAGE"], ...(opts.aspectRatio ? { imageConfig: { aspectRatio: opts.aspectRatio } } : {}) },
      };
  const res = await fetch(url, { method: "POST", headers, body: JSON.stringify(body), signal: opts.abortSignal });
  const json = (await res.json().catch(() => ({}))) as {
    error?: { message?: string };
    predictions?: { bytesBase64Encoded?: string; mimeType?: string }[];
    candidates?: { content?: { parts?: GeminiPart[] } }[];
  };
  if (!res.ok) throw new Error(json.error?.message || `Gemini image request failed (${res.status})`);
  if (imagen) {
    const p = json.predictions?.[0];
    if (!p?.bytesBase64Encoded) throw new Error("Imagen returned no image");
    return { base64: p.bytesBase64Encoded, mediaType: p.mimeType || "image/png" };
  }
  const part = json.candidates?.[0]?.content?.parts?.find((x) => x.inlineData?.data);
  if (!part?.inlineData?.data) throw new Error("Gemini returned no image");
  return { base64: part.inlineData.data, mediaType: part.inlineData.mimeType || "image/png" };
}
